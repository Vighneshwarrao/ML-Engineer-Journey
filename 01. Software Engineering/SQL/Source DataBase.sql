DROP DATABASE IF EXISTS CompanyDB;
CREATE DATABASE CompanyDB;
USE CompanyDB;

CREATE TABLE Departments (
department_id INT PRIMARY KEY AUTO_INCREMENT,
department_name VARCHAR(100), location VARCHAR(100));
CREATE TABLE Employees(
employee_id INT PRIMARY KEY AUTO_INCREMENT,
first_name VARCHAR(50),last_name VARCHAR(50),gender ENUM('Male','Female'),
hire_date DATE,salary DECIMAL(10,2),email VARCHAR(100) UNIQUE,phone VARCHAR(15),
manager_id INT NULL,department_id INT,
FOREIGN KEY(manager_id) REFERENCES Employees(employee_id),
FOREIGN KEY(department_id) REFERENCES Departments(department_id));
CREATE TABLE Projects(
project_id INT PRIMARY KEY AUTO_INCREMENT,
project_name VARCHAR(100),start_date DATE,end_date DATE,budget DECIMAL(12,2));
CREATE TABLE Employee_Projects(
employee_id INT,project_id INT,role VARCHAR(50),hours_worked INT,
PRIMARY KEY(employee_id,project_id),
FOREIGN KEY(employee_id) REFERENCES Employees(employee_id),
FOREIGN KEY(project_id) REFERENCES Projects(project_id));
CREATE TABLE Customers(
customer_id INT PRIMARY KEY AUTO_INCREMENT,
customer_name VARCHAR(100),city VARCHAR(100),country VARCHAR(100),email VARCHAR(100));
CREATE TABLE Orders(
order_id INT PRIMARY KEY AUTO_INCREMENT,
customer_id INT,order_date DATE,total_amount DECIMAL(10,2),status VARCHAR(20),
FOREIGN KEY(customer_id) REFERENCES Customers(customer_id));
CREATE TABLE Products(
product_id INT PRIMARY KEY AUTO_INCREMENT,
product_name VARCHAR(100),category VARCHAR(100),price DECIMAL(10,2),stock INT);
CREATE TABLE Order_Details(
order_id INT,product_id INT,quantity INT,price DECIMAL(10,2),
PRIMARY KEY(order_id,product_id),
FOREIGN KEY(order_id) REFERENCES Orders(order_id),
FOREIGN KEY(product_id) REFERENCES Products(product_id));
